"""Bundle anchor-plan layouts for the 3D viewer: python make_layouts.py [--fresh] [name ...] -> viewer/layouts.js

Default: every data/warrens*.json as it is; --fresh re-runs the design_warrens_v*.py scripts first.
layouts.js is a classic script (window.MARS_LAYOUTS = [...]) so index.html works from file:// with no server.
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLANS = HERE.parent
DATA = PLANS / 'data'
OUT = HERE / 'layouts.js'


def main(names):
    if '--fresh' in names:  # re-run every design script first (design_warrens_v3.py rewrites the LIVE data/warrens.json)
        names = [n for n in names if n != '--fresh']
        for script in sorted(PLANS.glob('design_warrens_v*.py')):
            subprocess.run([sys.executable, str(script)], check=True, cwd=PLANS)
    files = [DATA / f'{n}.json' for n in names] if names else sorted(DATA.glob('warrens*.json'))
    layouts = []
    for f in files:
        d = json.loads(f.read_text(encoding='utf-8'))
        d['_file'] = f.name
        layouts.append(d)
    layouts.sort(key=lambda d: (d['_file'] != 'warrens.json', str(d.get('revision', ''))))  # the live layout first
    OUT.write_text('// GENERATED by make_layouts.py; do not edit.\nwindow.MARS_LAYOUTS = ' + json.dumps(layouts) + ';\n', encoding='utf-8')
    print(f'wrote {OUT.name}: ' + ', '.join(f"{d['_file']} ({d.get('revision')})" for d in layouts))


if __name__ == '__main__':
    main(sys.argv[1:])
