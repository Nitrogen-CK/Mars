"""Emits an AngelScript anchor plan from a frozen map data file.

Usage (repo root):  python Tools/LevelDesign/anchor_plans/emit_plan.py warrens
                    python Tools/LevelDesign/anchor_plans/emit_plan.py warrens_v8c --plan WarrensC
Reads   Tools/LevelDesign/anchor_plans/data/<name>.json
Writes  Script/ECS/AnchorResolver/Plans/Mars_AnchorPlan_<Plan>.as   (never edit that file by hand)
<Plan> defaults to the data's `map`. --plan names a second plan over the same map's tags (a layout variant): the asset
Mars_AnchorPlan_<Plan>, its accessor utils_anchor_resolver::Plan_<Plan>() and its MapName (the run-history key) take the
plan name, while the anchor tags stay Anchor.Mars.<map>.*, so variants of one map share its registered tags.
Exit 1 if the data breaks a rule the AS Validate() also enforces, so a bad plan never reaches the editor.

Anchor ids are gameplay tags: an anchor id <Id> in the data is the tag Anchor.Mars.<Map>.<Id>, emitted through its
generated accessor GameplayTags::Anchor_Mars_<Map>_<Id>, so every id must be an identifier and every tag must be
registered in Config/DefaultGameplayTags.ini (the emitter checks both). Route-graph node ids stay FName.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def fail(msg):
    print("emit_plan: " + msg)
    sys.exit(1)


def f(v):
    return f"{float(v):.1f}"


def anchor_tag(title, aid):
    return f"Anchor.Mars.{title}.{aid}"


def anchor_accessor(title, aid):
    return "GameplayTags::" + anchor_tag(title, aid).replace(".", "_")


def registered_tags():
    ini = os.path.join(ROOT, "Config", "DefaultGameplayTags.ini")
    return set(re.findall(r'GameplayTagList=\(Tag="([^"]+)"', open(ini, encoding="utf-8").read()))


def main():
    args = sys.argv[1:]
    plan = None
    if len(args) == 3 and args[1] == "--plan":
        plan = args[2]
        args = args[:1]
    if len(args) != 1:
        fail("usage: emit_plan.py <name> [--plan <Plan>]")
    name = args[0].lower()
    src = os.path.join(ROOT, "Tools", "LevelDesign", "anchor_plans", "data", f"{name}.json")
    d = json.load(open(src, encoding="utf-8"))
    title = d["map"]
    plan = plan or title
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", plan):
        fail(f"plan name {plan} is not an identifier (it becomes the asset and accessor names)")
    nodes = d["nodes"]

    if len({nid.lower() for nid in nodes}) != len(nodes):
        fail("node ids must be unique ignoring case (FName compares case-insensitively)")
    if d["hearth"] not in nodes:
        fail("hearth is not a node")
    grouped = [a for g in d["groups"] for a in g["anchorIds"]]
    if len(grouped) != len(set(grouped)):
        fail("an anchor id is in two groups")
    for l in d["links"]:
        if l["a"] not in nodes or l["b"] not in nodes:
            fail(f"link {l['a']}-{l['b']} names an unknown node")
        if l["costCm"] <= 0:
            fail(f"link {l['a']}-{l['b']} has a non-positive cost")
        if l["closedBy"] and l["closedBy"] not in grouped:
            fail(f"{l['closedBy']} closes a link but is in no group")
    for e in d["entrances"] + d["courts"]:
        if e["node"] not in nodes:
            fail(f"{e['anchorId']} names an unknown node")
    for l in d["links"]:
        if l.get("leverNode") and (not l["closedBy"] or l["leverNode"] not in (l["a"], l["b"])):
            fail(f"link {l['a']}-{l['b']}: a lever node must be an end of a closable link")
    caches = d.get("caches", [])
    if len(caches) != len(set(caches)):
        fail("cache anchor ids must be unique")
    anchor_ids = grouped + [e["anchorId"] for e in d["entrances"] + d["courts"]] + caches
    tags = registered_tags()
    for aid in anchor_ids:
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", aid):
            fail(f"anchor id {aid} is not an identifier (it becomes the tag leaf and the GameplayTags:: accessor)")
        if anchor_tag(title, aid) not in tags:
            fail(f"{anchor_tag(title, aid)} is not registered in Config/DefaultGameplayTags.ini")

    out = []
    w = out.append
    w(f"// GENERATED by Tools/LevelDesign/anchor_plans/emit_plan.py from data/{name}.json. Do not edit: change the data and")
    w("// re-run the emitter. Source of the data: " + d["source"])
    w(f"// Anchor ids are the Anchor.Mars.{title}.* tags (Config/DefaultGameplayTags.ini); node ids are graph-internal names.")
    w("")
    w(f"asset Mars_AnchorPlan_{plan} of UMars_AnchorPlan_Def")
    w("{")
    w(f"    MapName = n\"{plan}\";")
    w(f"    Hearth = n\"{d['hearth']}\";")
    w(f"    QuarryMinWalkCm = {f(d['quarryMinWalkCm'])}f;")
    w(f"    SourceRevision = \"{d['source'].replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}\";")  # a quote in the source string must not end the literal
    w("")
    for nid in sorted(nodes):
        x, y, z = nodes[nid]
        w(f"    Nodes.Add(FMars_AnchorPlan_Node(n\"{nid}\", FVector({f(x * 100)}, {f(y * 100)}, {f(z * 100)})));")
    w("")
    for li, l in enumerate(d["links"]):
        closed = anchor_accessor(title, l["closedBy"]) if l["closedBy"] else "FGameplayTag()"
        w(f"    Links.Add(FMars_AnchorPlan_Link(n\"{l['a']}\", n\"{l['b']}\", {f(l['costCm'])}f, {closed}));")
        if l.get("leverNode"):
            w(f"    Links[{li}].LeverNode = n\"{l['leverNode']}\";")
    w("")
    for e in d["entrances"]:
        w(f"    Entrances.Add(FMars_AnchorPlan_Entrance({anchor_accessor(title, e['anchorId'])}, n\"{e['playerStartTag']}\", n\"{e['node']}\"));")
    for c in d["courts"]:
        w(f"    Courts.Add(FMars_AnchorPlan_Court({anchor_accessor(title, c['anchorId'])}, n\"{c['node']}\"));")
    w("")
    for gi, g in enumerate(d["groups"]):
        w(f"    Groups.Add(FMars_AnchorPlan_Group(n\"{g['name']}\", {g['maxClosed']}));")
        for a in g["anchorIds"]:
            w(f"    Groups[{gi}].AnchorIds.Add({anchor_accessor(title, a)});")
    if caches:
        w("")
        w(f"    MaxActiveCaches = {int(d.get('maxActiveCaches', 2))};")
        for a in caches:
            w(f"    Caches.Add({anchor_accessor(title, a)});")
    w("}")
    w("")
    w("namespace utils_anchor_resolver")
    w("{")
    w("    // Script assets resolve across files only through a namespace accessor in their own file.")
    w(f"    UMars_AnchorPlan_Def Plan_{plan}()")
    w(f"    {{ return Mars_AnchorPlan_{plan}; }}")
    w("}")
    w("")

    dst = os.path.join(ROOT, "Script", "ECS", "AnchorResolver", "Plans", f"Mars_AnchorPlan_{plan}.as")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"emit_plan: wrote {os.path.relpath(dst, ROOT)} ({len(nodes)} nodes, {len(d['links'])} links, "
          f"{len(d['entrances'])} entrances, {len(d['courts'])} courts)")


if __name__ == "__main__":
    main()
